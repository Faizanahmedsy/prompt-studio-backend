/** Platform-wide role. Decides who reaches the admin surface. */
export type GlobalRole = "SUPERADMIN" | "ADMIN" | "MEMBER"

/** Standing on ONE project. Unrelated to `GlobalRole`. Ordered by power. */
export type ProjectRole = "OWNER" | "EDITOR" | "COMMENTER" | "VIEWER"

/** Whether an invited address has been claimed by a real account yet. */
export type MemberStatus = "INVITED" | "ACTIVE" | "REVOKED"

export type ActivityType =
  | "PROJECT_CREATED"
  | "PROJECT_UPDATED"
  | "PROJECT_RENAMED"
  | "PROJECT_DELETED"
  | "PROJECT_RESTORED"
  | "MEMBER_INVITED"
  | "MEMBER_JOINED"
  | "MEMBER_ROLE_CHANGED"
  | "MEMBER_REMOVED"
  | "VERSION_SAVED"
  | "VERSION_RESTORED"
  | "COMMENT_ADDED"

/** `app/modules/rbac/permissions.py`. Platform permissions only — project
 *  access is the `ProjectRole` axis and is never expressed as a permission. */
export type PermissionCode =
  | "users.read"
  | "users.create"
  | "users.update"
  | "users.delete"
  | "users.set_role"
  | "projects.read_all"
  | "projects.delete_any"
  | "audit.read"
  | "stats.read"

export type ThemePreference = "light" | "dark" | "system"

/** `CommentCreate.target_kind` pattern. */
export type CommentTargetKind = "canvas" | "screen" | "module" | "edge"

/** Ranking used by the server (`ProjectRole.rank`), mirrored so the UI can ask
 *  "at least EDITOR?" without a second round trip. */
export const PROJECT_ROLE_RANK: Readonly<Record<ProjectRole, number>> = {
  VIEWER: 10,
  COMMENTER: 20,
  EDITOR: 30,
  OWNER: 40,
}

export function roleAtLeast(role: ProjectRole | null | undefined, floor: ProjectRole): boolean {
  if (!role) return false
  return PROJECT_ROLE_RANK[role] >= PROJECT_ROLE_RANK[floor]
}

