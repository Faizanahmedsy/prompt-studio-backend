export type ChangePasswordRequest = {
  current_password: string
  new_password: string
}

export type SetInitialPasswordRequest = { new_password: string }

export type ForgotPasswordRequest = { email: string }

/** Outside production the token comes back here so the flow is testable with no
 *  mail configured. In production it is always null. */
export type ForgotPasswordResponse = { reset_token: string | null }

export type ResetPasswordRequest = { token: string; new_password: string }

export type VerifyEmailRequest = { token: string }

