// ── users (app/modules/users/schemas.py) ─────────────────────────────────────

/** How a user appears *inside* something else — a member row, an activity
 *  entry, a presence list. Deliberately small; embedded many times per response. */
export type UserSummary = {
  id: Uuid
  email: string
  full_name: string
  avatar_url: string | null
  /** hex colour, e.g. "#4f46e5" */
  accent_color: string
}

export type UserRead = UserSummary & {
  role: GlobalRole
  is_active: boolean
  is_superuser: boolean
  email_verified_at: IsoDateTime | null
  last_login_at: IsoDateTime | null
  created_at: IsoDateTime
}

/**
 * `GET /users/me`. `permissions` exists so the UI can hide an admin link it
 * would only be 403'd on — a convenience, never the boundary. The same check
 * runs server-side on every admin route.
 */
export type UserMe = UserRead & {
  timezone: string
  theme: string
  /** Typed as `string[]`, not `PermissionCode[]`: a newer server may send a code
   *  this build has never heard of, and the type should not claim otherwise. */
  permissions: string[]
  must_change_password: boolean
  project_count: number
}

/** Self-service profile edits. Role and status are deliberately absent. */
export type UserUpdate = {
  full_name?: string | null
  avatar_url?: string | null
  /** must match /^#(?:[0-9a-fA-F]{3}){1,2}$/ */
  accent_color?: string | null
  timezone?: string | null
  theme?: ThemePreference | null
}

/** Admin list row: the account plus the numbers an operator scans for. */
export type UserListItem = UserRead & {
  project_count: number
  owned_project_count: number
  last_seen_at: IsoDateTime | null
}

export type AdminUserCreate = {
  email: string
  full_name?: string
  role?: GlobalRole
  /** Omit and one is generated, emailed, and returned once. */
  password?: string | null
  is_active?: boolean
  send_invite_email?: boolean
}

export type AdminUserUpdate = {
  full_name?: string | null
  role?: GlobalRole | null
  is_active?: boolean | null
  /** Issues a new password and re-flags the account. */
  reset_password?: boolean
}

